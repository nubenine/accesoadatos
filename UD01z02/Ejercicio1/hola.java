package UD01z02.Ejercicio1;

public class hola {
    public static void main(String[] args) {

        // Creamos dos numeros
        int numero1 = 10;
        int numero2 = 5;

        // Sumamos los dos numeros
        int suma = numero1 + numero2;

        // Mostramos el resultado por pantalla
        System.out.println("La suma es: " + suma);

        // Comprobamos si el resultado es mayor que 10
        if (suma > 10) {
            // Si es mayor, mostramos este mensaje
            System.out.println("La suma es mayor que 10"); //nigga/
        } else {
            // Si no es mayor, mostramos este otro
            System.out.println("La suma no es mayor que 10");
        }
    }
}
